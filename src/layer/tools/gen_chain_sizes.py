"""Generates src/layer/chain_sizes.inc: for every structure that vk.xml lists with
structextends=VkPresentInfoKHR / VkDeviceCreateInfo, a `case sType: return sizeof(Struct);` line.

  gen_chain_sizes.py <vulkan-headers dir> [--check <chain_sizes.inc>] > chain_sizes.inc

The headers dir holds include/vulkan/vulkan_core.h and registry/vk.xml. Structures that exist
only in platform headers or in the beta-extension blocks of vulkan_core.h are listed in
EXTRA_PRESENT (layout written out by hand) or skipped. With --check the output is compared with
the given file (exit 1 on a difference), which is what the pml_chain_table_check test does."""
import re
import sys
import xml.etree.ElementTree as ET

# Structures extending VkPresentInfoKHR that live in platform headers (not in vulkan_core.h).
# name -> (sType enum, size on LP64 and ILP32 as written by the header's own struct)
EXTRA_PRESENT = {
    "VkPresentFrameTokenGGP": ("VK_STRUCTURE_TYPE_PRESENT_FRAME_TOKEN_GGP", "sizeof(VkBaseInStructure) + 4"),
}
# Loader/layer interface structures that travel in the same chains but are not in vk.xml.
EXTRA_DEVICE = {
    "VkLayerDeviceCreateInfo": ("VK_STRUCTURE_TYPE_LOADER_DEVICE_CREATE_INFO", "sizeof(VkLayerDeviceCreateInfo)"),
}


def core_structs(path):
    """Names of structs defined in vulkan_core.h outside of beta-extension blocks."""
    names, depth_stack = set(), []
    for line in open(path, encoding="utf-8"):
        s = line.strip()
        if s.startswith("#ifdef") or s.startswith("#ifndef") or s.startswith("#if "):
            depth_stack.append("VK_ENABLE_BETA_EXTENSIONS" in s)
        elif s.startswith("#endif"):
            if depth_stack:
                depth_stack.pop()
        m = re.match(r"typedef struct (\w+) \{", s)
        if m and not any(depth_stack):
            names.add(m.group(1))
    return names


def collect(root, extended, available):
    out = {}
    for t in root.iter("type"):
        if t.get("category") != "struct" or t.get("alias") or t.get("api") == "vulkansc":
            continue
        ext = (t.get("structextends") or "").split(",")
        if extended not in ext:
            continue
        name = t.get("name")
        stype = None
        for m in t.findall("member"):
            if m.findtext("name") == "sType":
                stype = m.get("values")
        if name in available and stype:
            out[name] = stype
        else:
            out[name] = None
    return out


def main():
    args = sys.argv[1:]
    check = None
    if "--check" in args:
        i = args.index("--check")
        check = args[i + 1]
        del args[i:i + 2]
    base = args[0]
    root = ET.parse(base + "/registry/vk.xml").getroot()
    available = core_structs(base + "/include/vulkan/vulkan_core.h")
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by tools/gen_chain_sizes.py from vk.xml (structextends). Do not edit; the test",
        "// pml_chain_table_check regenerates it and compares.",
    ]
    for macro, extended, extra in (("PML_PRESENT_NODE", "VkPresentInfoKHR", EXTRA_PRESENT),
                                   ("PML_DEVICE_NODE", "VkDeviceCreateInfo", EXTRA_DEVICE)):
        table = collect(root, extended, available)
        lines.append("")
        lines.append("// structextends=%s" % extended)
        skipped = []
        for name in sorted(table):
            if name in extra:
                continue  # written below with its hand-made size
            if table[name]:
                lines.append("%s(%s, %s)" % (macro, table[name], name))
            else:
                skipped.append(name)
        for name in sorted(extra):
            lines.append("%s_SIZE(%s, %s)" % (macro, extra[name][0], extra[name][1]))
        for name in skipped:
            lines.append("// not copyable here (platform/beta header): %s" % name)
    text = "\n".join(lines) + "\n"
    if check:
        if open(check, encoding="utf-8").read() != text:
            sys.stderr.write("%s is out of date; regenerate with tools/gen_chain_sizes.py\n" % check)
            return 1
        return 0
    sys.stdout.write(text)
    return 0


sys.exit(main())
